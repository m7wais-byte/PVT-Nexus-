/* ======================================================= DAK solver */
test('DAK solver: converges everywhere in 0.2 ≤ Ppr ≤ 30, 1.05 ≤ Tpr ≤ 3.0 with residual < 1e-9; NaN outside, never a fake value', () => {
  const A = [0, 0.3265, -1.07, -0.5339, 0.01569, -0.05165, 0.5475, -0.7361, 0.1844, 0.1056, 0.6134, 0.721];
  const residual = (z, p, t) => {
    const r = 0.27 * p / (z * t), c1 = A[1] + A[2] / t + A[3] / t ** 3 + A[4] / t ** 4 + A[5] / t ** 5, c2 = A[6] + A[7] / t + A[8] / t ** 2, c3 = A[9] * (A[7] / t + A[8] / t ** 2), c4 = A[10] / t ** 3;
    return 1 + c1 * r + c2 * r * r - c3 * r ** 5 + c4 * r * r * (1 + A[11] * r * r) * Math.exp(-A[11] * r * r) - z;
  };
  let n = 0;
  for (let t = 1.05; t <= 3.0001; t += 0.05) for (let p = 0.2; p <= 30.0001; p *= 1.15) {
    const z = C.gas.z.dak(p, t); n++;
    assert.ok(z > 0 && Math.abs(residual(z, p, t)) < 1e-9, `Tpr ${t}, Ppr ${p}: ${z}`);
  }
  assert.ok(n > 1000);
  for (let t = 0.7; t <= 1.05; t += 0.01) for (let p = 0.05; p <= 40; p *= 1.2) {
    const z = C.gas.z.dak(p, t);
    assert.ok(Number.isNaN(z) || (z > 0 && Math.abs(residual(z, p, t)) < 1e-9), 'outside range: NaN or a true root');
  }
  /* at the critical isotherm the equation has three roots; starting from Z = 1 the solver returns the gas-like one */
  assert.ok(Math.abs(C.gas.z.dak(0.919, 1.0) - 0.4926) < 1e-3);
});

