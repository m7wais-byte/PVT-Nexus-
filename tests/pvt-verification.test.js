/* ======================================================= cg: consistent with the selected Z and corrected pseudo-criticals */
test('real-gas cg equals the analytic DAK derivative, using the sour-corrected pseudo-criticals', () => {
  const A = [0, 0.3265, -1.07, -0.5339, 0.01569, -0.05165, 0.5475, -0.7361, 0.1844, 0.1056, 0.6134, 0.721];
  /* cpr = 1/Ppr − (0.27/(Z²·Tpr))·(∂Z/∂ρr)/(1 + (ρr/Z)·∂Z/∂ρr)   (Mattar, Brar & Aziz 1975 form); cg = cpr/Ppc */
  function cgAnalytic(p, tR, ppc, tpc) {
    const ppr = p / ppc, t = tR / tpc, z = C.gas.z.dak(ppr, t), r = 0.27 * ppr / (z * t);
    const c1 = A[1] + A[2] / t + A[3] / t ** 3 + A[4] / t ** 4 + A[5] / t ** 5, c2 = A[6] + A[7] / t + A[8] / t ** 2, c3 = A[9] * (A[7] / t + A[8] / t ** 2);
    const dz = c1 + 2 * c2 * r - 5 * c3 * r ** 4 + (2 * A[10] * r / t ** 3) * (1 + A[11] * r * r - A[11] * A[11] * r ** 4) * Math.exp(-A[11] * r * r);
    return (1 / ppr - (0.27 / (z * z * t)) * dz / (1 + (r / z) * dz)) / ppc;
  }
  const comp = [{ name: 'Methane', y: '0.80' }, { name: 'Carbon dioxide', y: '0.12' }, { name: 'Hydrogen sulfide', y: '0.08' }];
  for (const sour of ['none', 'wichert_aziz']) {
    const r = E.run({ fluid: 'gas', units: 'field', calcMode: 'list', pList: '800 2500 6000', T: '180', gasBasis: 'composition', comp, m: { pc: 'kay', sour, z: 'dak', mu: 'lee_gonzalez_eakin' } });
    assert.equal(r.ok, true);
    r.pressures.forEach((p, i) => near(r.props.cg.values[i], cgAnalytic(p, r.ctx.tR, r.pc.ppc, r.pc.tpc), 2e-5, `cg ${sour} at ${p}`));
  }
});

/* ======================================================= physical reference: GERG-2008 (CoolProp) */
const GNAME = { Methane: 'Methane', Ethane: 'Ethane', Propane: 'Propane', 'n-Butane': 'n-Butane', Nitrogen: 'Nitrogen', CarbonDioxide: 'Carbon dioxide', HydrogenSulfide: 'Hydrogen sulfide' };
function gergRun(gas, pt, m, byGravity) {
  const comp = Object.entries(GERG.gases[gas].composition).map(([k, y]) => ({ name: GNAME[k], y: String(y) }));
  const base = { fluid: 'gas', units: 'field', calcMode: 'single', p: String(pt.p), T: String(pt.T), m: Object.assign({ pc: 'kay', sour: 'none', z: 'dak', mu: 'lee_gonzalez_eakin' }, m) };
  if (!byGravity) return E.run(Object.assign(base, { gasBasis: 'composition', comp }));
  const c = E.run(Object.assign({}, base, { gasBasis: 'composition', comp, m: { pc: 'kay', sour: 'none', z: 'dak', mu: 'lee_gonzalez_eakin' } })).ctx;
  return E.run(Object.assign(base, { gasBasis: 'gravity', gg: String(c.gg), yCO2: String(c.yCO2), yH2S: String(c.yH2S), yN2: String(c.yN2) }));
}
function gergStats(gas, m, byGravity) {
  const ez = [], er = [], ec = [];
  GERG.gases[gas].points.forEach((pt) => {
    const r = gergRun(gas, pt, m, byGravity);
    assert.equal(r.ok, true, JSON.stringify(r.errors));
    ez.push(100 * rel(r.props.z.values[0], pt.Z)); er.push(100 * rel(r.props.rho.values[0], pt.rho)); ec.push(100 * rel(r.props.cg.values[0], pt.cg));
  });
  const mx = (a) => Math.max(...a.map(Math.abs));
  return { z: aare(ez), zMax: mx(ez), rho: aare(er), rhoMax: mx(er), cg: aare(ec), cgMax: mx(ec) };
}

test('molar mass of the reference gases matches GERG (component table check)', () => {
  for (const g of ['sweet', 'sour']) {
    const r = gergRun(g, GERG.gases[g].points[0], {}, false);
    near(r.ctx.ma, GERG.gases[g].molar_mass, 2e-4, g);
  }
});

